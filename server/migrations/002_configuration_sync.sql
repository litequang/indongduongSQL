CREATE TABLE IF NOT EXISTS settings (
 id TINYINT PRIMARY KEY CHECK(id=1), company_name VARCHAR(120) NOT NULL, short_name VARCHAR(40) NOT NULL,
 phone VARCHAR(30) NOT NULL DEFAULT '', address VARCHAR(250) NOT NULL DEFAULT '', website VARCHAR(250) NOT NULL DEFAULT '', slogan VARCHAR(160) NOT NULL DEFAULT '',
 primary_color CHAR(7) NOT NULL DEFAULT '#2563eb', acceptance_minutes INT UNSIGNED NOT NULL DEFAULT 30,
 plate_minutes INT UNSIGNED NOT NULL DEFAULT 60, printing_minutes INT UNSIGNED NOT NULL DEFAULT 60,
 poll_interval_ms INT UNSIGNED NOT NULL DEFAULT 4000 CHECK(poll_interval_ms BETWEEN 3000 AND 30000),
 version INT UNSIGNED NOT NULL DEFAULT 1, updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS setting_options (
 category VARCHAR(20) NOT NULL, position SMALLINT UNSIGNED NOT NULL, value VARCHAR(100) NOT NULL,
 PRIMARY KEY(category,position), UNIQUE KEY uq_setting_option(category,value)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 action VARCHAR(60) NOT NULL, entity_id VARCHAR(80) NOT NULL, details JSON NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT fk_audit_actor FOREIGN KEY(actor_id) REFERENCES users(id), INDEX ix_audit_created(created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS change_events (
 sequence BIGINT UNSIGNED PRIMARY KEY, entity VARCHAR(20) NOT NULL, entity_id VARCHAR(80) NOT NULL,
 record_version INT UNSIGNED NOT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX ix_changes_entity(entity,sequence)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
